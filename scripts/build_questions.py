SOURCE = Path(__file__).resolve().parents[1] / 'content' / 'بنك_أسئلة_معلومات_عامة_10000.txt'
DEST = Path(__file__).resolve().parents[1] / 'src' / 'data' / 'questions.json'

category_map = {
    'الجغرافيا والبلدان والمدن': 'geography',
    'العلوم والفضاء': 'science',
    'التاريخ والحضارات': 'history',
    'الأدب والفنون': 'arts',
    'السينما والثقافة': 'culture',
    'التقنية والحاسوب': 'technology',
    'الرياضة والألعاب': 'sports',
    'اللغة العربية': 'language',
    'الطبيعة والإنسان': 'nature',
    'الرياضيات والمنطق': 'math',
}

raw = SOURCE.read_text(encoding='utf-8')
current = None
records = []
lines = raw.splitlines()
for index, line in enumerate(lines):
    heading = re.match(r'^\[\s*(.*?)\s*—\s*[\d,]+\s+سؤال\s*\]$', line)
    if heading:
        current = category_map.get(heading.group(1).strip())
        continue
    question_match = re.match(r'^\d+\.\s*س:\s*(.+)$', line)
    if not question_match or current is None:
        continue
    question = question_match.group(1).strip()
    answer = ''
    for following in lines[index + 1:index + 4]:
        answer_match = re.match(r'^\s*ج:\s*(.+)$', following)
        if answer_match:
            answer = answer_match.group(1).strip()
            break
    if answer:
        records.append({
            'id': f'general-{len(records) + 1}',
            'category': current,
            'question': question,
            'answer': answer,
            'origin': 'general',
        })

